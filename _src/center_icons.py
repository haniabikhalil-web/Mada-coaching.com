"""Optical centring for every icon on the site. Run after adding or changing an icon:

    python3 _src/center_icons.py

An icon drawn on a 24x24 canvas is rarely drawn around the canvas centre (a magnifier sits top-left, a speech bubble
sits high), so it looks off-centre in its box even when the box is perfectly centred. This measures the real drawing
bounds of every icon in a headless browser and writes the shift that puts the middle of the drawing on the middle
of the canvas: into _src/icon_nudge.py (the build's icons) and into the NUDGE block of assets/js/mada-ui.js (the
interactive pages' icons). Needs Python playwright and a Chrome at /usr/bin/google-chrome (or set CHROME).
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import build  # noqa: E402  (ICONS)
from playwright.sync_api import sync_playwright  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
UI_JS = os.path.join(HERE, '..', 'assets', 'js', 'mada-ui.js')
CHROME = os.environ.get('CHROME', '/usr/bin/google-chrome')
# Shapes whose weight sits to one side get a small extra shift towards where their mass is (a play triangle is
# centred on the midpoint of its bounds and its centre of mass, which is what the eye reads as the middle).
MASS_BLEND = {'play': 0.5}


def js_markup(parts):
    out = []
    for d in parts:
        out.append('<circle cx="12" cy="12" r="9"/>' if d == 'circle' else f'<path d="{d}"/>')
    return ''.join(out)


def measure(page, markup):
    return page.evaluate("""(m) => {
        const g = document.getElementById('g'); g.innerHTML = m; const b = g.getBBox();
        return [b.x, b.y, b.width, b.height];
    }""", markup)


def main():
    with sync_playwright() as p:
        br = p.chromium.launch(executable_path=CHROME, args=['--no-sandbox'])
        page = br.new_page()
        page.set_content('<svg viewBox="0 0 24 24" width="24" height="24"><g id="g"></g></svg>')
        # The interactive pages' icons come from mada-ui.js itself
        page.add_script_tag(path=UI_JS)
        js_icons = page.evaluate('window.MadaUI.icons')
        py_nudge, js_nudge = {}, {}

        def shift(box, name, markup=''):
            x, y, w, h = box
            cx, cy = x + w / 2, y + h / 2
            if name in MASS_BLEND and 'circle' not in markup:   # play: pull the target towards the centroid of a right-pointing triangle
                cx = cx + (x + w / 3 * 1 - cx) * 0 + (-(w / 2 - w / 3)) * MASS_BLEND[name] * 0
                cx = cx - (w / 2 - w / 3) * MASS_BLEND[name]
            return round(12 - cx, 2), round(12 - cy, 2)

        for name, markup in build.ICONS.items():
            dx, dy = shift(measure(page, markup), name, markup)
            if abs(dx) >= 0.1 or abs(dy) >= 0.1:
                py_nudge[name] = (dx, dy)
        for name, parts in js_icons.items():
            dx, dy = shift(measure(page, js_markup(parts)), name, js_markup(parts))
            if abs(dx) >= 0.1 or abs(dy) >= 0.1:
                js_nudge[name] = [dx, dy]
        br.close()

    with open(os.path.join(HERE, 'icon_nudge.py'), 'w') as f:
        f.write('# Generated by _src/center_icons.py. Do not edit by hand.\nNUDGE = {\n')
        for k in sorted(py_nudge):
            f.write(f"    {k!r}: {py_nudge[k]!r},\n")
        f.write('}\n')
    src = open(UI_JS).read()
    block = '  // NUDGE:BEGIN\n  var NUDGE = ' + json.dumps(js_nudge, sort_keys=True, separators=(',', ':')) + ';\n  // NUDGE:END'
    src = re.sub(r'  // NUDGE:BEGIN.*?// NUDGE:END', lambda m: block, src, flags=re.S)
    open(UI_JS, 'w').write(src)
    print('build icons shifted:', len(py_nudge), '| interactive icons shifted:', len(js_nudge))


if __name__ == '__main__':
    main()
